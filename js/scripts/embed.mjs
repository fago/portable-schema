// Writes js/src/embedded.ts: the meta-schemas of spec/v1, the type library of types/v1 and messages/en.json, as JSON
// text. The JS validator imports them instead of reading files, so it also runs bundled and in a browser.
// Run by the build and test scripts of js/package.json and by scripts/compare-results.sh; the output is not committed.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("../../", import.meta.url);

/** The JSON text of a file, without insignificant whitespace. */
const json = (path) => {
  try {
    return JSON.stringify(JSON.parse(readFileSync(new URL(path, ROOT), "utf8")));
  } catch (error) {
    throw new Error(`The file ${path} is not valid JSON: ${error.message}`);
  }
};

/** The *.json files below a directory, by the rules of Registry.addDirectory(). */
const files = (directory, prefix = "") =>
  readdirSync(new URL(`${directory}/${prefix}`, ROOT), { withFileTypes: true }).flatMap((entry) => {
    if (entry.name.startsWith(".") || entry.isSymbolicLink()) return [];
    if (entry.isDirectory()) return files(directory, `${prefix}${entry.name}/`);
    return entry.name.endsWith(".json") && !entry.name.endsWith(".test.json") ? [prefix + entry.name] : [];
  });

const spec = ["vocab.json", "schema.json", "schema-strict.json"].map((file) => [file, json(`spec/v1/${file}`)]);
// In the order of Registry.addDirectory(), but without its percent-decoding: no type needs it.
const types = files("types/v1").sort().map((file) => {
  if (file.includes("%")) throw new Error(`The file types/v1/${file} has a percent-encoded name: embed.mjs does not decode it.`);
  return [file.slice(0, -".json".length), json(`types/v1/${file}`)];
});

/** An object literal of JSON texts: a JSON string is a JS string literal. */
const literal = (entries) => `{\n${entries.map(([key, text]) => `  ${JSON.stringify(key)}: ${JSON.stringify(text)},\n`).join("")}}`;

writeFileSync(new URL("js/src/embedded.ts", ROOT), `// Generated by js/scripts/embed.mjs from spec/v1, types/v1 and messages/en.json. Do not edit.

/** The meta-schemas of spec/v1: JSON text by file name. */
export const SPEC: Readonly<Record<${spec.map(([file]) => JSON.stringify(file)).join(" | ")}, string>> = ${literal(spec)};

/** The type library of types/v1: JSON text by id, without the namespace. */
export const TYPES: Readonly<Record<string, string>> = ${literal(types)};

/** The message catalog messages/en.json, as JSON text. */
export const MESSAGES: string = ${JSON.stringify(json("messages/en.json"))};
`);
